import { describe, expect, it } from "vitest";
import { buildReply, isAutoGenerated } from "./reply";
import { canReplyTo } from "./inbound";
import type { ParsedEmail } from "./inbound";

describe("buildReply", () => {
  it("summarises mixed results", () => {
    const { subject, text } = buildReply({
      orgName: "Acme",
      subject: "RE: Re: COI for job 4",
      results: [
        { filename: "a.pdf", status: "compliant", issues: [] },
        {
          filename: "b.pdf",
          status: "non_compliant",
          issues: [{ code: "expired", severity: "error", message: "Policy expired 3 day(s) ago." }],
        },
      ],
      errors: ["c.pdf: model error"],
    });
    expect(subject).toBe("Re: COI for job 4 - 1 of 2 need attention");
    expect(text).toContain("[OK] a.pdf - Compliant");
    expect(text).toContain("[FAIL] b.pdf - Not compliant");
    expect(text).toContain("- Policy expired 3 day(s) ago.");
    expect(text).toContain("c.pdf: model error");
  });
  it("handles no results", () => {
    const { subject, text } = buildReply({ orgName: "Acme", subject: "", results: [], errors: [] });
    expect(subject).toBe("Re: your documents - No documents could be checked");
    expect(text).toContain("didn't find a PDF");
  });
});

describe("auto-reply guards", () => {
  it("detects automated mail", () => {
    expect(isAutoGenerated({ "auto-submitted": "auto-replied" }, "a@b.com")).toBe(true);
    expect(isAutoGenerated({ "auto-submitted": "no" }, "a@b.com")).toBe(false);
    expect(isAutoGenerated({ precedence: "bulk" }, "a@b.com")).toBe(true);
    expect(isAutoGenerated({ "list-id": "<x>" }, "a@b.com")).toBe(true);
    expect(isAutoGenerated({}, "no-reply@b.com")).toBe(true);
    expect(isAutoGenerated({}, "mailer-daemon@b.com")).toBe(true);
    expect(isAutoGenerated({}, "sparky@b.com")).toBe(false);
  });
  const mail = (over: Partial<ParsedEmail>): ParsedEmail => ({
    messageId: "m",
    sender: "sparky@example.com",
    subject: "",
    tokens: [],
    headers: { "received-spf": "pass (example.com: ...)" },
    attachments: [],
    ...over,
  });
  it("requires SPF pass by default", () => {
    expect(canReplyTo(mail({}), true)).toBe(true);
    expect(canReplyTo(mail({ headers: {} }), true)).toBe(false);
    expect(canReplyTo(mail({ headers: { "received-spf": "fail" } }), true)).toBe(false);
    expect(canReplyTo(mail({ headers: {} }), false)).toBe(true);
  });
  it("rejects invalid sender addresses", () => {
    expect(canReplyTo(mail({ sender: "not an address" }), false)).toBe(false);
  });
});
