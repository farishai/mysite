import type { Issue } from "./schema";
import type { Status } from "./rules";

export interface ReplyResult {
  filename: string;
  status: Status;
  issues: Issue[];
}

const MARK: Record<Status, string> = { compliant: "OK", warning: "CHECK", non_compliant: "FAIL" };
const LABEL: Record<Status, string> = {
  compliant: "Compliant",
  warning: "Needs attention",
  non_compliant: "Not compliant",
};

/** Plain-text summary sent back to whoever emailed the documents. Pure, so it is easy to test. */
export function buildReply(opts: {
  orgName: string;
  subject: string;
  results: ReplyResult[];
  errors: string[];
}): { subject: string; text: string } {
  const { orgName, results, errors } = opts;
  const bad = results.filter((r) => r.status !== "compliant").length;
  const base = opts.subject.replace(/^(re:\s*)+/i, "").trim() || "your documents";

  const headline =
    results.length === 0
      ? "No documents could be checked"
      : bad === 0
        ? `${results.length} compliant`
        : `${bad} of ${results.length} need attention`;

  const lines: string[] = [`We checked the documents you sent to ${orgName}'s SubPaper inbox.`, ""];
  for (const r of results) {
    lines.push(`[${MARK[r.status]}] ${r.filename} - ${LABEL[r.status]}`);
    for (const i of r.issues) lines.push(`    - ${i.message}`);
  }
  if (results.length === 0) lines.push("We didn't find a PDF, PNG or JPEG certificate to check.");
  if (errors.length) {
    lines.push("", "Problems:");
    for (const e of errors) lines.push(`    - ${e}`);
  }
  lines.push("", "This is an automatic message. Fix any issues and send the updated document to the same address.");
  return { subject: `Re: ${base} - ${headline}`, text: lines.join("\n") };
}

const AUTO_LOCALPARTS = /^(no-?reply|do-?not-?reply|mailer-daemon|postmaster|bounce[s]?|notifications?)$/i;

/** Don't answer machines: loops and backscatter cost money and annoy people. */
export function isAutoGenerated(headers: Record<string, string>, sender: string): boolean {
  const auto = headers["auto-submitted"];
  if (auto && auto.toLowerCase() !== "no") return true;
  if (/^(bulk|junk|list|auto_reply)$/i.test(headers["precedence"] ?? "")) return true;
  if ("x-autoreply" in headers || "x-autorespond" in headers || "list-id" in headers) return true;
  return AUTO_LOCALPARTS.test(sender.split("@")[0] ?? "");
}
